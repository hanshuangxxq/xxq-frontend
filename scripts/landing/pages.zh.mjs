function zhPage(slug, data) {
  return {
    lang: 'zh-CN',
    slug,
    urlPath: slug === '' ? '/' : `/${slug}/`,
    outPath: slug === '' ? 'landing.html' : `${slug}/index.html`,
    indexable: true,
    ...data,
  }
}

